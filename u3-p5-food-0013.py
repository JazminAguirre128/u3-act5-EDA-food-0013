import pandas as pd
import matplotlib.pyplot as plt
# Meredith Aguirre NC 0013
# 1. Leer el archivo CSV desde el archivo de indian food
df_food_india = pd.read_csv('indian_food.csv')
print("\n--- DATOS LEÍDOS DESDE CSV Meredith Aguirre 0013---")
print(df_food_india)
print("\n--- MOSTRAR NOMBRE COMIDA + INGREDIENTES Meredith Aguirre 0013---")
recetas = df_food_india[['name', 'ingredients']]
print(recetas)
print("\n--- TIEMPO DE COCINADO MOSTRAR 10 REGISTROS CON HEAD Meredith Aguirre 0013---")
nombre_y_hora = df_food_india[['name', 'cook_time']].head(10)
print(nombre_y_hora)
print("\n--- GRAFICA COMIDA (X) TIEMPO DE COCINADO (Y) Meredith Aguirre 0013---")
print("\n--- GRAFICA COMIDA (X) TEXTO A 30 GRADOS Meredith Aguirre 0013---")
nombre_y_hora.plot.bar(x='name',y='cook_time', rot=30)
plt.title('Comida tipíca de la India Meredith Aguirre 0013')
plt.xlabel('Nombre del platillo')
plt.ylabel('Tiempo de cocinado')
plt.show()
nombre_y_hora = df_food_india[['name', 'prep_time', 'cook_time']].head(10)
nombre_y_hora.plot.bar(x='name', rot=30)
plt.title('Grafica de 2 columnas Meredith Aguirre 0013')
plt.xlabel('Nombre del platillo')
plt.ylabel('Tiempo de cocinado')
plt.show()
print("\n--- GRAFICA APILADAS UNA TRAS OTRA VERTICALMENTE Meredith Aguirre 0013---")
nombre_y_hora.plot.bar(x='name', stacked=True, rot=30)
plt.title('Grafica de 2 columnas Meredith Aguirre 0013')
plt.xlabel('Graficas apiladas')
plt.ylabel('Tiempo de cocinado')
plt.show()